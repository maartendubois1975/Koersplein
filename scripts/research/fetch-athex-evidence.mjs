import fs from 'node:fs/promises';
import {reconcile} from './reconcile-isin.mjs';
const root='https://portal.athexgroup.gr/web/guest/rds/-/rdsFile/';
const index=await fetch(root+'PROD_LatestReports_csv');
if(!index.ok)throw Error('RDS index HTTP '+index.status);
const manifest=await index.text();
const filename=manifest.split(/\r?\n/).map(line=>line.split(';')[3]).find(x=>/^InstrumentSeries_\d{8}_G_v\d+\.csv$/.test(x));
if(!filename)throw Error('Official Athens InstrumentSeries not in manifest');
const url=root+'PROD_'+filename.replace(/\.csv$/, '_csv');
const response=await fetch(url);
if(!response.ok)throw Error('Official InstrumentSeries HTTP '+response.status+' '+url);
const bytes=Buffer.from(await response.arrayBuffer());
const text=new TextDecoder('iso-8859-7').decode(bytes);
const catalog=JSON.parse(await fs.readFile(new URL('../../data/euronext-athens.json',import.meta.url)));
const date=filename.match(/\d{8}/)[0].replace(/(\d{4})(\d{2})(\d{2})/,'$1-$2-$3');
const evidence=text.split(/\r?\n/).map(line=>line.split(';')).filter(fields=>fields.length>20).map(fields=>({symbol:fields[0].trim(),isin:(fields[18]||'').trim(),sourceUrl:url,sourceDate:date,sourceDocument:filename}));
const report=reconcile(catalog,evidence.filter(e=>catalog.shares.some(s=>s.symbol===e.symbol)));
await fs.mkdir('research/output/audit',{recursive:true});
await fs.writeFile('research/output/audit/athens-isin-evidence.json',JSON.stringify(report,null,2));
console.log(JSON.stringify({url,bytes:bytes.length,rows:evidence.length,accepted:report.accepted.length,rejected:report.rejected.length,remaining:report.unresolved,examples:evidence.slice(0,3)}));
if(!report.accepted.length)throw Error('No verified Athens ISINs found; inspect official RDS columns');
