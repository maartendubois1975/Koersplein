import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {listingIdentity,marketManifest} from './block2-identity-core.mjs';
const market={mic:'XAMS'};
const base={symbol:'TEST',isin:'US0378331005',instrumentType:'COMMON_STOCK'};
const valid=listingIdentity(base,market);
assert.equal(valid.identity.isin,base.isin);
assert.equal(listingIdentity({...base,symbol:'test'},market).identityHash,valid.identityHash);
const caseDuplicate=marketManifest(market,[base,{...base,symbol:'test'}]);
assert.ok(caseDuplicate.listings[1].issues.includes('DUPLICATE_SYMBOL'));
assert.ok(caseDuplicate.listings[1].issues.includes('DUPLICATE_LISTING_IDENTITY'));
assert.ok(listingIdentity({...base,providerSymbol:'OTHER'},market).issues.includes('CONFLICTING_SYMBOL_FIELDS'));
assert.ok(!listingIdentity({...base,providerSymbol:'test'},market).issues.includes('CONFLICTING_SYMBOL_FIELDS'));
assert.equal(listingIdentity({...base,providerSymbol:'   '},market).identity.symbol,'TEST');
assert.ok(marketManifest(market,[{...base,providerSymbol:'   '},base]).listings[1].issues.includes('DUPLICATE_SYMBOL'));
assert.equal(valid.certified,false);
assert.ok(valid.issues.includes('INDEPENDENT_SOURCE_VERIFICATION_REQUIRED'));
assert.ok(listingIdentity({...base,isin:null},market).issues.includes('MISSING_ISIN'));
assert.ok(listingIdentity({...base,symbol:''},market).issues.includes('MISSING_SYMBOL'));
assert.equal(listingIdentity({...base,symbol:''},market).certified,false);
assert.ok(listingIdentity({...base,isin:'INVALID'},market).issues.includes('INVALID_ISIN'));
assert.ok(listingIdentity({...base,mic:'XPAR'},market).issues.includes('WRONG_MIC'));
assert.ok(listingIdentity({...base,instrumentType:'ETF'},market).issues.includes('UNVERIFIED_TYPE'));
const manifest=marketManifest(market,[base,base]);
assert.equal(manifest.total,2);
assert.equal(manifest.certified,0);
assert.ok(manifest.listings[1].issues.includes('DUPLICATE_SYMBOL'));
assert.ok(manifest.listings[1].issues.includes('DUPLICATE_LISTING_IDENTITY'));
const missingIsinDuplicates=marketManifest(market,[{...base,isin:null},{...base,isin:null}]);
assert.ok(missingIsinDuplicates.listings[1].issues.includes('DUPLICATE_SYMBOL'));
assert.ok(missingIsinDuplicates.listings[1].issues.includes('MISSING_ISIN'));
assert.equal(missingIsinDuplicates.certified,0);
assert.equal(listingIdentity({...base,isin:'us0378331005'},market).identity.isin,'US0378331005');
assert.equal(manifest.listings[0].identityHash,manifest.listings[1].identityHash);
const athens=JSON.parse(await fs.readFile('data/euronext-athens.json','utf8'));
const sourcedAthens=athens.shares.filter(row=>row.identitySource==='https://www.athexgroup.gr/sites/default/files/2025-10/ENPR20251013ATHEXGROUP.pdf');
assert.equal(sourcedAthens.length,34); // EUROB moved to the December successor-listing primary source
assert.equal(athens.shares.find(row=>row.symbol==='ETE').isin,'GRS003003035');
assert.equal(athens.shares.find(row=>row.symbol==='ALPHA').isin,'GRS830003000');
assert.ok(sourcedAthens.every(row=>row.identityResolution.includes('CERTIFICATION_PENDING')||row.identityResolution.includes('CERTIFICATION_BLOCKED')));
assert.ok(athens.shares.find(row=>row.symbol==='EUROB').identityCorporateActionSource.includes('EUROBANK_Prospectus_2025.pdf'));
assert.equal(athens.shares.find(row=>row.symbol==='EUROB').isin,'GRS829003003');
assert.equal(athens.shares.find(row=>row.symbol==='EUROB').previousIsin,'GRS323003012');
assert.ok(athens.shares.find(row=>row.symbol==='EUROB').identitySource.includes('2025-12/'));
assert.ok(athens.shares.find(row=>row.symbol==='EUROB').identityResolution.includes('MERGER'));
assert.ok(sourcedAthens.every(row=>listingIdentity(row,{mic:'XATH'}).certified===false));
const aprilAthens=athens.shares.filter(row=>row.identitySource==='https://www.athexgroup.gr/sites/default/files/2026-04/ENPR20260407ATHEXGROUP.pdf');
assert.equal(aprilAthens.length,89);
assert.equal(athens.shares.filter(row=>!row.isin).length,21);
assert.equal(athens.shares.find(row=>row.symbol==='TPEIR').isin,'GRS831003009');
assert.equal(athens.shares.find(row=>row.symbol==='BYLOT').isin,'GRS343313003');
assert.ok(aprilAthens.every(row=>listingIdentity(row,{mic:'XATH'}).certified===false));
const eee=athens.shares.find(row=>row.symbol==='EEE');
assert.equal(eee.isin,'CH0198251305');
assert.ok(eee.identitySource.startsWith('https://www.athexgroup.gr/'));
assert.equal(listingIdentity(eee,{mic:'XATH'}).certified,false);
const warsaw=JSON.parse(await fs.readFile('data/euronext-warsaw.json','utf8'));
const eurocash=warsaw.shares.find(row=>row.symbol==='EUR');
assert.equal(eurocash.isin,'PLEURCH00011');
assert.equal(eurocash.identitySource,'https://www.grupaeurocash.pl/dla-inwestora/informacje-gieldowe');
assert.ok(eurocash.identityCrossCheckSource.startsWith('https://www.bankier.pl/'));
assert.equal(listingIdentity(eurocash,{mic:'XWAR'}).certified,false);
console.log('PASS Block 2 deterministic identities, duplicates and independent-verification lock');
