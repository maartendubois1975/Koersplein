import fs from 'node:fs/promises';
import crypto from 'node:crypto';
const configPath=process.argv[2];
if(!configPath)throw Error('Usage: node block1-v2-snapshot-adapter.mjs <source-config.json>');
const c=JSON.parse(await fs.readFile(configPath,'utf8'));
if(!c.mic||!c.sourceUrl||!c.inputFile||!c.fields?.symbol||!c.fields?.isin||!c.fields?.securityType)throw Error('Incomplete source configuration');
const source=new URL(c.sourceUrl);
if(source.protocol!=='https:')throw Error('Official source URL must use HTTPS');
const raw=await fs.readFile(c.inputFile,'utf8');
const json=JSON.parse(raw);
const rows=c.recordsPath?c.recordsPath.split('.').reduce((a,k)=>a?.[k],json):json;
if(!Array.isArray(rows))throw Error('Source records must be an array');
const field=(r,path)=>path.split('.').reduce((a,k)=>a?.[k],r);
const records=rows.map(r=>({symbol:field(r,c.fields.symbol),isin:field(r,c.fields.isin),securityType:field(r,c.fields.securityType)}));
const snapshot={mic:c.mic,sourceUrl:c.sourceUrl,retrievedAt:new Date().toISOString(),sourceContentSha256:crypto.createHash('sha256').update(raw).digest('hex'),sourceSnapshotIndependentlyVerified:false,records};
await fs.mkdir('research/output/block1-official-snapshots',{recursive:true});
const file='research/output/block1-official-snapshots/'+c.mic+'.json';
await fs.writeFile(file,JSON.stringify(snapshot,null,2));
console.log(JSON.stringify({mic:c.mic,records:records.length,file,reviewRequired:true}));
