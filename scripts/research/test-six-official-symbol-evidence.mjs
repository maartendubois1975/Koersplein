import assert from 'node:assert/strict';
import {officialSixUrl,evaluateSixPage,selectSwissCandidates,fetchOfficialSixHtml,probeSwissReference} from './six-official-symbol-evidence.mjs';
const item={mic:'XSWX',isin:'FR0000125007',symbol:'490580',currency:'CHF'};
const url=officialSixUrl(item);
assert.equal(url,'https://www.six-group.com/en/market-data/shares/share-explorer/share-details.FR0000125007CHF4.html');
const html='<html><head><title>SAINT GOBAIN I Stock Price - GOB | SIX</title></head><body>ISIN FR0000125007</body></html>';
assert.equal(evaluateSixPage(item,html,url).status,'OFFICIAL_ISIN_SYMBOL_EVIDENCE');
assert.equal(evaluateSixPage(item,html,url).symbol,'GOB');
assert.equal(evaluateSixPage(item,html.replace('FR0000125007','CH0000000001'),url).status,'TITLE_ONLY_ISIN_NOT_PROVEN');
assert.equal(evaluateSixPage(item,html,url+'?redirect=1').status,'OFFICIAL_URL_MISMATCH');
assert.equal(evaluateSixPage(item,html.replace(' - GOB',' - 123456'),url).status,'NUMERIC_VALOR_NOT_SYMBOL');
assert.equal(evaluateSixPage(item,html+'<title>duplicate</title>',url).status,'OFFICIAL_TITLE_NOT_UNIQUE');
assert.throws(()=>officialSixUrl({...item,currency:'GBP'}),/INVALID/);
assert.throws(()=>officialSixUrl({...item,mic:'XPAR'}),/INVALID/);
const shares=[item,{...item,isin:'CH0000000001',symbol:'12345'}, {...item,isin:'CH0000000002',symbol:'12346',providerSymbol:'TEST.SW'}, {...item,isin:'CH0000000003',symbol:'TEST'}];
assert.equal(selectSwissCandidates(shares,{limit:12}).length,2);
assert.equal(selectSwissCandidates(shares,{limit:1,rotation:1}).length,1);
assert.throws(()=>selectSwissCandidates(shares,{limit:100}),/LIMIT/);
let requested=0;
const report=await probeSwissReference([item],{fetchHtml:async()=>{requested++;return html;}});
assert.equal(requested,1);assert.equal(report.requested,1);assert.equal(report.statuses.OFFICIAL_ISIN_SYMBOL_EVIDENCE,1);
assert.equal(report.results[0].approvedForProduction,false);
const failed=await probeSwissReference([item],{fetchHtml:async()=>{throw Error('timeout');}});
assert.equal(failed.statuses.OFFICIAL_FETCH_FAILED,1);
await assert.rejects(()=>fetchOfficialSixHtml('http://evil.invalid/a'),/UNAPPROVED/);
const fake=async u=>({ok:true,url:u,headers:{get:k=>k==='content-type'?'text/html':null},text:async()=>html});
assert.equal(await fetchOfficialSixHtml(url,fake),html);
await assert.rejects(()=>fetchOfficialSixHtml(url,async u=>({...await fake(u),url:'https://evil.invalid'})),/URL_MISMATCH/);
console.log('SIX official read-only symbol evidence tests PASS');