import assert from 'node:assert/strict';
import {pricePatternFeatures,anomalyLoserGuard,peerRelativeFeatures} from './machine-specialists-core.mjs';
const bars=Array.from({length:300},(_,i)=>({date:new Date(Date.UTC(2020,0,1+i)).toISOString().slice(0,10),close:100+i*.2,volume:100}));
const f=pricePatternFeatures(bars,299);
assert(f&&f.momentum250d>0&&f.momentum120d>0);
assert.equal(anomalyLoserGuard(f).guardActive,false);
const a={features:{momentum120d:.3}},b={features:{momentum120d:.1}},c={features:{momentum120d:.2}};
const p=peerRelativeFeatures(a,[a,b,c]);
assert.equal(p.peerCount,2);
assert(p.relativeMomentum120d>0);
assert.equal(p.percentile,1);
const crash=anomalyLoserGuard({volatility120:.08,distance250dHigh:-.5,momentum60d:-.3,momentum20d:-.4,momentum120d:-.1});
assert.equal(crash.guardActive,true);
assert.equal(crash.warnings.length,4);
console.log(JSON.stringify({status:'PASS',pattern:f,peer:p,crash}));
