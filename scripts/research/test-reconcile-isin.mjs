import assert from 'node:assert/strict';
import {reconcile} from './reconcile-isin.mjs';
const catalog={mic:'XATH',shares:[{symbol:'EEE',isin:null},{symbol:'ETE',isin:null}]};
const good={symbol:'EEE',isin:'CH0198251305',sourceUrl:'https://example.org/official',sourceDate:'2026-10-16',sourceDocument:'official instrument record'};
const result=reconcile(catalog,[good,{...good,symbol:'ETE',isin:'BAD'},{...good}]);
assert.equal(result.accepted.length,1);
assert.equal(result.rejected.length,2);
assert.equal(result.unresolved,1);
assert.throws(()=>reconcile({...catalog,mic:'XAMS'},[good]));
console.log('ISIN evidence gate tests passed');
