import assert from 'node:assert/strict';
import {normalizeCatalog} from './block1-v2-core.mjs';
const m={mic:'XAMS',currency:'EUR'};
const proof={securityType:'ORDINARY_SHARE',securityTypeSource:'Official issuer list',securityTypeSourceUrl:'https://example.org/issuer',securityTypeVerifiedAt:'2026-10-14'};
const a={symbol:'AAA',isin:'NL0000235190',...proof};
const b={symbol:'BBB',isin:'NL0000235190',...proof};
const invalid={symbol:'CCC',isin:'XICE:CCC',...proof};
const x=normalizeCatalog(m,[a,b,invalid]);
assert.equal(x.summary.input,3);
assert.equal(x.summary.acceptedListings,2);
assert.equal(x.summary.distinctSecurities,1);
assert.equal(x.summary.rejected,1);
assert.deepEqual(x.rejected[0].issues,['INVALID_ISIN']);
const d=normalizeCatalog(m,[a,a]);
assert(d.rejected.some(r=>r.issues.includes('DUPLICATE_LISTING_KEY')));
const missing=normalizeCatalog(m,[{symbol:'DDD',isin:'NL0000235190'}]);
assert(missing.rejected[0].issues.includes('UNVERIFIED_SECURITY_TYPE'));
console.log('Block 1 v2 core selftest PASS');
