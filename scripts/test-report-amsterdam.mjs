import assert from 'node:assert/strict';
import {mkdtemp,writeFile,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
const dir=await mkdtemp(join(tmpdir(),'xams-report-'));
const path=join(dir,'report.json');
const script=new URL('./report-amsterdam.mjs',import.meta.url).pathname;
const manifest=JSON.parse(await readFile(new URL('../data/amsterdam-history-manifest.json',import.meta.url),'utf8'));
const isins=Object.keys(manifest.instruments);
assert.equal(isins.length,80);
const run=async report=>{
 await writeFile(path,JSON.stringify(report));
 const p=spawnSync(process.execPath,[script,path],{encoding:'utf8'});
 assert.ok(p.stdout,'report must be printed even on validation failure');
 return {status:p.status,summary:JSON.parse(p.stdout)};
};
const sample={market:'XAMS',date:'2026-10-29',approved:0,candidates:isins.slice(0,76).map(isin=>({isin})),noTrade:isins.slice(76,79).map(isin=>({isin})),missing:[{isin:isins[79],status:'NO_SOURCE_ROW'}],errors:[]};
let result=await run(sample);
assert.equal(result.status,0);
assert.equal(result.summary.complete,true);
assert.equal(result.summary.accounted,80);
assert.equal(result.summary.exceptions[3].isin,isins[79]);
sample.missing=[];
result=await run(sample);
assert.notEqual(result.status,0);
assert.deepEqual(result.summary.missingIsins,[isins[79]]);
sample.missing=[{isin:isins[0]}];
result=await run(sample);
assert.notEqual(result.status,0);
assert.deepEqual(result.summary.duplicateIsins,[isins[0]]);
assert.deepEqual(result.summary.missingIsins,[isins[79]]);
sample.missing=[{isin:'FAKE_ISIN'}];
result=await run(sample);
assert.notEqual(result.status,0);
assert.deepEqual(result.summary.unknownIsins,['FAKE_ISIN']);
console.log('PASS Amsterdam report: exact 80 ISIN coverage, missing, duplicate and unknown rejected');
