import assert from 'node:assert/strict';
import {mkdtemp,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
const dir=await mkdtemp(join(tmpdir(),'xams-report-'));
const path=join(dir,'report.json');
const script=new URL('./report-amsterdam.mjs',import.meta.url).pathname;
const run=()=>spawnSync(process.execPath,[script,path],{encoding:'utf8'});
const sample={date:'2026-10-29',approved:0,candidates:Array.from({length:76},(_,i)=>({isin:'TEST_'+i})),noTrade:Array.from({length:3},(_,i)=>({isin:'NOTRADE_'+i})),missing:[{isin:'TEST_MISSING',status:'NO_SOURCE_ROW_LISTING_CHECK_REQUIRED'}],errors:[]};
await writeFile(path,JSON.stringify(sample));
let result=run();
assert.equal(result.status,0);
assert.equal(JSON.parse(result.stdout).accounted,80);
assert.equal(JSON.parse(result.stdout).exceptions.at(-1).isin,'TEST_MISSING');
sample.missing=[];
await writeFile(path,JSON.stringify(sample));
result=run();
assert.notEqual(result.status,0);
assert.equal(JSON.parse(result.stdout).accounted,79);
sample.missing=[{isin:'TEST_0'}];
await writeFile(path,JSON.stringify(sample));
result=run();
assert.notEqual(result.status,0,'duplicate ISIN must be rejected even when total is 80');
assert.deepEqual(JSON.parse(result.stdout).duplicateIsins,['TEST_0']);
console.log('PASS Amsterdam daily report: 80 unique accounted, 79 flagged, duplicate ISIN rejected');
