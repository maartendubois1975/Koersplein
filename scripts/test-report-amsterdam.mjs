import assert from 'node:assert/strict';
import {mkdtemp,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
const dir=await mkdtemp(join(tmpdir(),'xams-report-'));
const path=join(dir,'report.json');
const script=new URL('./report-amsterdam.mjs',import.meta.url).pathname;
const run=()=>spawnSync(process.execPath,[script,path],{encoding:'utf8'});
const sample={date:'2026-10-29',approved:0,candidates:Array(76).fill({}),noTrade:Array(3).fill({}),missing:[{}],errors:[]};
await writeFile(path,JSON.stringify(sample));
let result=run();
assert.equal(result.status,0);
assert.equal(JSON.parse(result.stdout).accounted,80);
sample.missing=[];
await writeFile(path,JSON.stringify(sample));
result=run();
assert.notEqual(result.status,0);
assert.equal(JSON.parse(result.stdout).accounted,79);
console.log('PASS Amsterdam daily report: 80 accounted, 79 flagged');
