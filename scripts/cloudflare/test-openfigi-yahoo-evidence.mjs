const goodSwiss=evaluateYahooReference(swiss,swissChart,{asOf:'2026-10-22'});
assert.equal(goodSwiss.status,'YAHOO_VENUE_CURRENCY_OHLC_MATCH_OFFICIAL_ISIN_STILL_REQUIRED');
assert.equal(goodSwiss.latestCompleteDate,'2026-10-21');
assert.equal(goodSwiss.readOnly,true);
assert.equal(evaluateYahooReference(swiss,{...swissChart,meta:{...swissChart.meta,symbol:'WRONG.SW'}},{asOf:'2026-10-22'}).status,'YAHOO_SYMBOL_MISMATCH');
assert.equal(evaluateYahooReference(swiss,{...swissChart,meta:{...swissChart.meta,exchangeName:'NOT SIX'}},{asOf:'2026-10-22'}).status,'YAHOO_VENUE_UNVERIFIED');
assert.equal(evaluateYahooReference(swiss,{...swissChart,meta:{...swissChart.meta,currency:'USD'}},{asOf:'2026-10-22'}).status,'YAHOO_CURRENCY_MISMATCH');
assert.equal(evaluateYahooReference(swiss,{...swissChart,bars:[{...bar,high:null}]},{asOf:'2026-10-22'}).status,'NO_RECENT_COMPLETE_YAHOO_OHLC');
assert.equal(evaluateYahooReference(swiss,{...swissChart,bars:[{...bar,date:'2026-08-01'}]},{asOf:'2026-10-22'}).status,'NO_RECENT_COMPLETE_YAHOO_OHLC');
assert.equal(evaluateYahooReference({...swiss,currency:null},swissChart,{asOf:'2026-10-22'}).status,'CATALOG_CURRENCY_UNKNOWN');
assert.equal(evaluateYahooReference({...swiss,candidates:[{ticker:'BAD',providerSymbol:'BAD.L'}]},swissChart,{asOf:'2026-10-22'}).status,'UNSAFE_REFERENCE_SYMBOL');
assert.equal(evaluateYahooReference(ambiguous,swissChart,{asOf:'2026-10-22'}).status,'NOT_UNIQUE_OFFICIAL_MIC_REFERENCE');
const londonChart={meta:{symbol:'HEAD.L',exchangeName:'LSE',currency:'GBp'},bars:[bar]};
assert.equal(evaluateYahooReference(london,londonChart,{asOf:'2026-10-22'}).status,'YAHOO_VENUE_CURRENCY_OHLC_MATCH_OFFICIAL_ISIN_STILL_REQUIRED');
