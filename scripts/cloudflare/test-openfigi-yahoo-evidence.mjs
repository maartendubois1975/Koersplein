import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {normalizeQuoteCurrency,selectOpenFigiYahooCandidates,findOpenFigiSymbolCollisions,evaluateYahooReference,fetchYahooReferenceChart} from './openfigi-yahoo-evidence.mjs';

const swiss={mic:'XSWX',isin:'AT0000KTMI02',catalogSymbol:'41860974',currency:'CHF',classification:'REFERENCE_CANDIDATE_REQUIRES_INDEPENDENT_VERIFICATION',candidates:[{ticker:'BMAG',providerSymbol:'BMAG.SW'}]};
const london={mic:'XLON',isin:'GB0004170089',catalogSymbol:'HEAD',currency:'GBX',classification:'REFERENCE_CANDIDATE_REQUIRES_INDEPENDENT_VERIFICATION',candidates:[{ticker:'HEAD',providerSymbol:'HEAD.L'}]};
const other={...london,isin:'GB0000000002',candidates:[{ticker:'XYZ',providerSymbol:'XYZ.L'}]};
const ambiguous={...swiss,isin:'CH0000000003',classification:'AMBIGUOUS_MULTIPLE_TICKERS',candidates:[{ticker:'A',providerSymbol:'A.SW'},{ticker:'B',providerSymbol:'B.SW'}]};
const report={mode:'READ_ONLY_NO_PRICE_WRITES',items:[london,ambiguous,swiss,other]};
const selection=selectOpenFigiYahooCandidates(report,{offset:0,limit:2});
assert.equal(selection.totalEligible,3);
assert.equal(selection.ambiguousDeferred,1);
assert.deepEqual(selection.items.map(x=>x.isin),[swiss.isin,london.isin]);
assert.deepEqual(selectOpenFigiYahooCandidates(report,{offset:2,limit:2}).items.map(x=>x.isin),[other.isin]);
assert.throws(()=>selectOpenFigiYahooCandidates(report,{offset:-1}),/Invalid/);
assert.throws(()=>selectOpenFigiYahooCandidates(report,{limit:101}),/Invalid/);
assert.throws(()=>selectOpenFigiYahooCandidates({...report,mode:'WRITE'}),/read-only/);
assert.equal(normalizeQuoteCurrency('GBp'),'GBX');
assert.equal(normalizeQuoteCurrency('GBX'),'GBX');
assert.equal(normalizeQuoteCurrency('GBP'),'GBP');
assert.notEqual(normalizeQuoteCurrency('GBP'),normalizeQuoteCurrency('GBp'));
const collisions=findOpenFigiSymbolCollisions({...report,items:[swiss,{...swiss,isin:'CH0000000004'}]});
assert.ok(collisions.has('BMAG.SW'));
assert.equal(findOpenFigiSymbolCollisions(report).size,0);
const bar={date:'2026-10-21',open:10,high:11,low:9,close:10.5};
