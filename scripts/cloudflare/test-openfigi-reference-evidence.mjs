import assert from 'node:assert/strict';
import {figiJob,classifyFigiEvidence} from './openfigi-reference-evidence.mjs';
const swiss={mic:'XSWX',isin:'AT0000KTMI02',symbol:'41860974',currency:'CHF'};
const london={mic:'XLON',isin:'GB0000000001',symbol:'ABC',currency:'GBP'};
assert.deepEqual(figiJob(swiss),{idType:'ID_ISIN',idValue:'AT0000KTMI02',micCode:'XSWX',includeUnlistedEquities:true});
assert.throws(()=>figiJob({...swiss,mic:'XLUX'}),/Unsupported MIC/);
assert.throws(()=>figiJob({...swiss,isin:'NOT_AN_ISIN'}),/invalid ISIN/);
const good={figi:'BBG000000001',ticker:'BMAG',exchCode:'SE',marketSector:'Equity',name:'SIX listed company',securityType:'Common Stock'};
const mapped=classifyFigiEvidence(swiss,{data:[good,{...good,exchCode:'SW',ticker:'COMPOSITE'},{...good,exchCode:'LN',ticker:'OTHER'}]});
assert.equal(mapped.classification,'REFERENCE_CANDIDATE_REQUIRES_INDEPENDENT_VERIFICATION');
assert.deepEqual(mapped.candidates.map(x=>x.providerSymbol),['BMAG.SW']);
assert.equal(mapped.catalogSymbol,'41860974');
assert.equal(mapped.currency,'CHF');
assert.equal(classifyFigiEvidence(swiss,{data:[{...good,ticker:'FIRST'},{...good,ticker:'SECOND'}]}).classification,'AMBIGUOUS_MULTIPLE_TICKERS');
assert.equal(classifyFigiEvidence(swiss,{data:[{...good,exchCode:'SW'}]}).classification,'NO_VERIFIED_MARKET_MATCH');
assert.equal(classifyFigiEvidence(swiss,{warning:'No identifier found.'}).classification,'NO_MATCH');
assert.equal(classifyFigiEvidence(swiss,{error:'HTTP error'}).classification,'SOURCE_ERROR');
const londonMapped=classifyFigiEvidence(london,{data:[{...good,ticker:'ABC',exchCode:'LN'},{...good,ticker:'ABC',exchCode:'LI'}]});
assert.equal(londonMapped.classification,'REFERENCE_CANDIDATE_REQUIRES_INDEPENDENT_VERIFICATION');
assert.deepEqual(londonMapped.candidates.map(x=>x.providerSymbol),['ABC.L']);
assert.equal(classifyFigiEvidence(london,{data:[{...good,exchCode:'SE'}]}).classification,'NO_VERIFIED_MARKET_MATCH');
console.log('OpenFIGI read-only ISIN/MIC and exchange-specific candidate safety PASS');
