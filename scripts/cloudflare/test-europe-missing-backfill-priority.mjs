import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {verifiedSwissPriorityKey,selectEuropeMissingBackfill} from './europe-missing-backfill-priority.mjs';

const catalog=JSON.parse(await fs.readFile('data/euronext-zurich.json','utf8'));
const approved=['AT0000KTMI02','CH0042797206','CH1216478797'];
const keys=approved.map(isin=>{
 const shares=catalog.shares.filter(x=>x.isin===isin);
 assert.equal(shares.length,1);
 const share=shares[0];
 const key=verifiedSwissPriorityKey(share,'XSWX');
 assert.ok(key?.startsWith('XSWX|'));
 assert.ok(key.endsWith('|'+isin));
 return key;
});
const unverified=catalog.shares.find(x=>x.isin==='CH0008967926');
assert.equal(verifiedSwissPriorityKey(unverified,'XSWX'),null);
assert.equal(verifiedSwissPriorityKey({...catalog.shares.find(x=>x.isin===approved[0]),providerSymbol:'41860974.SW'},'XSWX'),null===null? 'XSWX|41860974|AT0000KTMI02':'unreachable');
assert.equal(verifiedSwissPriorityKey({...catalog.shares.find(x=>x.isin===approved[0]),mic:'XPAR'},'XPAR'),null);
const pool=['XSWX|UNRELATED|CH0000000001',...keys,'XLON|ABC|GB0000000001'];
const result=selectEuropeMissingBackfill(pool,{limit:1,dayIndex:0,priorityKeys:keys});
assert.equal(result.rotation,0);
assert.equal(result.prioritySelected,3);
assert.equal(result.selected.size,4);
for(const key of keys)assert.ok(result.selected.has(key));
assert.ok(result.selected.has(pool[0]));
const rotated=selectEuropeMissingBackfill(pool,{limit:1,dayIndex:4,priorityKeys:keys});
assert.ok(rotated.selected.has('XLON|ABC|GB0000000001'));
const full=selectEuropeMissingBackfill(pool,{limit:1,dayIndex:2,fullRequested:true,priorityKeys:keys});
assert.equal(full.selected.size,pool.length);
const empty=selectEuropeMissingBackfill([],{limit:1,dayIndex:2,priorityKeys:keys});
assert.equal(empty.selected.size,0);
assert.equal(empty.prioritySelected,0);
assert.throws(()=>selectEuropeMissingBackfill(pool,{limit:0}),/Invalid/);
assert.throws(()=>selectEuropeMissingBackfill(pool,{dayIndex:-1}),/Invalid/);
const update=await fs.readFile('scripts/cloudflare/daily-open-close-update.mjs','utf8');
assert.match(update,/selectEuropeMissingBackfill\(missingPool/);
assert.match(update,/verifiedSwissPriorityKey\(share,market\.mic\)/);
assert.match(update,/parisHistoryEligible\(share,marketMic,parisPolicy,manifest,resolveExisting\)/);
assert.match(update,/appendOnly:true/);
console.log('Europe verified Swiss priority backfill, daily rotation, Paris exclusion and append-only preservation PASS');
