import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {auditEuropeSourceCoverage} from './europe-source-coverage-evidence.mjs';
const registry=JSON.parse(await fs.readFile('data/market-source-registry.json','utf8'));
const snapshot=JSON.stringify(registry);
const audit=auditEuropeSourceCoverage(registry);
assert.equal(audit.mode,'READ_ONLY_SOURCE_COVERAGE_AUDIT');
assert.equal(audit.sourceApprovalChanges,0);
assert.equal(audit.productionMappingsCreated,0);
assert.equal(JSON.stringify(registry),snapshot,'Source audit must never mutate approved registry');
const byMic=mic=>audit.markets.find(x=>x.mic===mic);
assert.equal(byMic('XSWX').catalog,445);
assert.equal(byMic('XSWX').chartCovered,216);
assert.equal(byMic('XSWX').discoveryImpliedCovered,443);
assert.equal(byMic('XSWX').coverageNotExplainedByDirectChart,227);
assert.equal(byMic('XSWX').classification,'DISCOVERY_VS_DIRECT_CHART_ATTRIBUTION_REQUIRED');
assert.equal(byMic('XCYS').chartCovered,0);
assert.equal(byMic('XCYS').coverageNotExplainedByDirectChart,38);
assert.equal(byMic('XLON').coverageNotExplainedByDirectChart,3);
assert.equal(byMic('XLON').blockedReason,'SOURCE_PREFLIGHT_GATE');
assert.equal(byMic('XBUL').classification,'OTHER_PRIMARY_SOURCE_ATTRIBUTION_REVIEW','BSE official source is distinct from zero Yahoo preflight');
assert.equal(byMic('XPAR'),undefined,'No quantified preflight is not evidence of zero source coverage');
const inconsistent=auditEuropeSourceCoverage({markets:{TEST:{discovery:{testedFullCatalog:4,coverageRatio:0.5},historySources:[{provider:'yahoo-chart',role:'PRIMARY',note:'Full-catalog preflight: 3/5 instruments.'}]}}});
assert.equal(inconsistent.markets[0].classification,'PREFLIGHT_METADATA_INCONSISTENT');
assert.equal(inconsistent.markets[0].coverageNotExplainedByDirectChart,null);
console.log('Read-only source preflight audit PASS: XSWX 227, XCYS 38, XLON 3 direct-chart attribution gaps; official alternative preserved');
