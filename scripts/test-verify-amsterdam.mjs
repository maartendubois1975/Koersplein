import assert from 'node:assert/strict';
import {mkdtemp,writeFile,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
const dir=await mkdtemp(join(tmpdir(),'xams-verify-'));
const source=join(dir,'source.json'),target=join(dir,'verified.json');
const date='2026-10-29',isin='NL0000852564';
const row={isin,symbol:'AALB',mic:'XAMS',date,open:10,high:12,low:9,close:11,volume:100,source:'Euronext public historical table',sourceUrl:'https://live.euronext.com/en/ajax/getHistoricalPricePopup/'+isin+'-XAMS',retrievedAt:'2026-10-30T08:00:00Z',sourceVerified:false,sessionClosedVerified:false};
const script=new URL('./verify-amsterdam.mjs',import.meta.url).pathname;
const run=()=>spawnSync(process.execPath,[script,source,target],{encoding:'utf8'});
await writeFile(source,JSON.stringify({market:'XAMS',date,candidates:[row,{...row,isin:'WRONG'},{...row,isin:'NL0011540547',symbol:'ABN',sourceUrl:'https://evil.example/'}]}));
assert.equal(run().status,0,'valid source should pass with isolated bad rows');
let result=JSON.parse(await readFile(target,'utf8'));
assert.equal(result.rows.length,1);
assert.equal(result.rejected.length,2);
assert.equal(result.rows[0].sourceVerified,true);
assert.equal(result.rows[0].sessionClosedVerified,true);
await writeFile(source,JSON.stringify({market:'XAMS',date:'2099-10-29',candidates:[row]}));
assert.notEqual(run().status,0,'future session must fail');
console.log('PASS verified Euronext source, isolated invalid rows and rejected future sessions');
