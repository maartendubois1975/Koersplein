import assert from 'node:assert/strict';
import {mkdtemp,writeFile,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
const dir=await mkdtemp(join(tmpdir(),'xams-stage-'));
const source=join(dir,'source.json'),target=join(dir,'review.json');
await writeFile(source,JSON.stringify({market:'XAMS',date:'2026-11-03',candidates:[{isin:'NL0000852564',symbol:'AALB',sourceVerified:true,sessionClosedVerified:true}]}));
const script=new URL('./stage-amsterdam-review.mjs',import.meta.url).pathname;
const result=spawnSync(process.execPath,[script,source,target],{encoding:'utf8'});
assert.equal(result.status,0,result.stderr);
const review=JSON.parse(await readFile(target,'utf8'));
assert.equal(review.reviewRequired,true);
assert.equal(review.rows.length,1);
assert.equal(review.rows[0].sourceVerified,false);
assert.equal(review.rows[0].sessionClosedVerified,false);
console.log('PASS Amsterdam staging: no unverified data automatically approved');
