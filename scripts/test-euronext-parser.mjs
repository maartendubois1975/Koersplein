import assert from 'node:assert/strict';
import {parseRows,parsePrice} from './euronext-parser.mjs';
assert.equal(parsePrice('12,34'),12.34);
assert.equal(parsePrice('-'),null);
const html='<table><tr><th>Date</th><th>Open</th><th>Close</th><th>Volume</th></tr><tr><td>30/10/2026</td><td>12,34</td><td>12,50</td><td>1200</td></tr></table>';
const rows=parseRows(html);
assert.equal(rows.length,1);
assert.equal(rows[0].open,12.34);
assert.equal(rows[0].close,12.5);
assert.equal(rows[0].volume,1200);
assert.throws(()=>parseRows('<table></table>'));
console.log('PASS Euronext parser fixtures');
