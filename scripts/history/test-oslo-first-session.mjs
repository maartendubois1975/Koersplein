import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { parseEuronextHistoryRows } from './providers/euronext-live.mjs';
import { inspectDailyBarIntegrity } from '../cloudflare/europe-run-policy.mjs';
const read = file => fs.readFile(file, 'utf8').then(JSON.parse);
const old = await read('research/oslo/2026-11-26/candidate-companies.json');
const current = await read('research/oslo/2026-11-27/candidate-companies.json');
const source = await read('research/oslo/2026-11-27/heder-first-session.json');
assert.equal(old.shares.length, 243); assert.equal(current.shares.length, 244);
for (const share of old.shares) assert.deepEqual(current.shares.find(row => row.isin === share.isin), share);
assert.equal(new Set(current.shares.map(row => row.isin)).size, 244);
assert.equal(new Set(current.shares.map(row => row.symbol)).size, 244);
assert.equal(source.quote.identityMatch, true); assert.equal(source.quote.currency, 'NOK');
assert.equal(source.quote.lastTradeDate, '2026-11-26');
assert.deepEqual(parseEuronextHistoryRows(source.tableHtml), source.bars);
assert.equal(source.bars.length, 1);
assert.equal(source.bars[0].date, '2026-11-26');
assert.equal(inspectDailyBarIntegrity({ bars: source.bars }, { startDate: '2026-11-26', endDate: '2026-11-26' }).conflicts.length, 0);
const summary = await read('research/oslo/2026-11-27/summary.json');
assert.equal(summary.counts.INCLUDE, 244); assert.equal(summary.operationalAdmission, false);
assert.equal((await read('data/company-register-contracts.json')).markets.XOSL, undefined);
console.log('Oslo first closed Heder session: exact NOK/ISIN, 243 existing candidates preserved, 244 research-only companies PASS');
