import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';
import { auditEuronextFile } from './audit-euronext-trade-file.mjs';
import { reconcileTradeDetails } from './reconcile-euronext-trade-details.mjs';
const root = 'research/milan/2026-11-27/';
const all = JSON.parse(await readFile(root + 'official-daily-observations.json', 'utf8'));
const selected = all.filter(row => ['A2A', 'ALMS', 'PRO', 'EDAC', 'KME'].includes(row.symbol));
const lines = gunzipSync(await readFile(root + 'real-trade-fixture.csv.gz')).toString().trimEnd().split(/\r?\n/);
const audit = await auditEuronextFile(lines, selected, '2026-11-26', 'MTAA', { listingDetails: true });
const result = reconcileTradeDetails(audit, selected);
assert.equal(result.volumeMatches, 5);
const a2a = result.listings.find(row => row.symbol === 'A2A');
assert.equal(a2a.trades.darkVolume, 17086);
assert.equal(a2a.trades.totalVolume, 4971756);
assert.equal(a2a.official.volume - a2a.trades.bookVolume, 17086);
const alms = result.listings.find(row => row.symbol === 'ALMS');
assert.equal(alms.trades.offBookVolume, 30751);
assert.equal(alms.trades.totalVolume, 36381);
const edac = result.listings.find(row => row.symbol === 'EDAC');
assert.equal(edac.status, 'DEFINITION_REVIEW');
assert.equal(edac.exactFinalIntervalVwapMatch, true);
assert.notEqual(edac.trades.last.price, edac.official.close);
assert.equal(result.publicationApproved, false);
const duplicated = await auditEuronextFile([...lines, lines[2]], selected, '2026-11-26', 'MTAA', { listingDetails: true });
assert.deepEqual(duplicated.listings, audit.listings, 'Repeated trade ID must not duplicate volume');
const changed = structuredClone(selected); changed[0].bar.date = '2026-11-25';
assert.throws(() => reconcileTradeDetails(audit, changed), /SESSION_MISMATCH/);
assert.throws(() => reconcileTradeDetails(audit, [...selected, selected[0]]), /IDENTITY_MISMATCH/);
const full = JSON.parse(await readFile(root + 'session-reconciliation.json', 'utf8'));
assert.equal(full.approved, 360); assert.equal(full.observed, 309);
assert.equal(full.volumeMatches, 309); assert.equal(full.volumeDifferences, 0);
assert.equal(full.statuses.DEFINITION_REVIEW, 15);
console.log('Real Milan book/dark/off-book volumes, reference close, deduplication and identity/session rejection PASS');
